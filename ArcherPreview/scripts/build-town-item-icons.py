"""Pack artist-approved item PNGs into the 0.3 menu atlas (Python + Pillow and Node)."""
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import subprocess

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
COLUMNS, CELL, PADDING = 8, 128, 4
ART = ROOT / "src/v03/art/town-item-icons.webp"
CSS = ROOT / "src/v03/town-item-icons.css"
# The alpha trophy uses the wolf fang cutout and the blade uses the same equipped shape and finish.
SOURCE_ICONS = {"alpha-wolf-fang": "wolf-fang", "alpha-fang-blade": "wolf-blade"}


def catalog(node):
    script = ("import {TOWN_ITEMS} from './src/v03/town-items.js';"
              "console.log(JSON.stringify(Object.entries(TOWN_ITEMS)"
              ".map(([id,item])=>[id,item.slot?'equipment':'supplies',"
              "item.slot?[item.slot,item.finish,item.profile].join('/'):id])));")
    return json.loads(subprocess.check_output(
        [node, "--input-type=module", "-e", script], cwd=ROOT, encoding="utf-8"))


def source_tile(path):
    with Image.open(path) as source:
        if source.format != "PNG" or ("A" not in source.getbands() and "transparency" not in source.info):
            raise ValueError(f"Expected a transparent PNG: {path}")
        rgba = source.convert("RGBA")
    alpha = rgba.getchannel("A")
    bounds = alpha.point(lambda a: 255 if a >= 8 else 0).getbbox()
    visible = sum(alpha.histogram()[8:]) / (rgba.width * rgba.height)
    if not bounds or visible >= .98:
        raise ValueError(f"Missing cutout or opaque background: {path}")
    crop = rgba.crop(bounds)
    scale = (CELL - 2 * PADDING) / max(crop.size)
    dimensions = tuple(max(1, round(axis * scale)) for axis in crop.size)
    # Pillow resizes RGBA in premultiplied space so transparent edges keep their color.
    cut = crop.resize(dimensions, Image.Resampling.LANCZOS)
    tile = Image.new("RGBA", (CELL, CELL))
    tile.paste(cut, ((CELL - cut.width) // 2, (CELL - cut.height) // 2))
    return tile


def stylesheet(items, rows):
    lines = [
        "/* Generated by scripts/build-town-item-icons.py from the town catalog. */",
        ".mf-town-item-icon {",
        "  display: inline-block;",
        "  inline-size: var(--mf-item-icon-size, 2.5rem);",
        "  block-size: var(--mf-item-icon-size, 2.5rem);",
        "  flex: none;",
        "  vertical-align: middle;",
        '  background-image: url("./art/town-item-icons.webp");',
        "  background-repeat: no-repeat;",
        f"  background-size: {100 * COLUMNS}% {100 * rows}%;",
        "  background-position: var(--mf-item-x, 200%) var(--mf-item-y, 200%);",
        "}",
    ]
    for index, (item_id, _, _) in enumerate(items):
        x = 100 * (index % COLUMNS) / max(1, COLUMNS - 1)
        y = 100 * (index // COLUMNS) / max(1, rows - 1)
        lines.append(f'.mf-town-item-icon[data-item-icon="{item_id}"] {{ --mf-item-x: {x:.6f}%; --mf-item-y: {y:.6f}%; }}')
    return ("\n".join(lines) + "\n").encode()


def pack(items, source):
    rows = math.ceil(len(items) / COLUMNS)
    sheet = Image.new("RGBA", (COLUMNS * CELL, rows * CELL))
    def icon_path(item_id, group):
        return source / group / (SOURCE_ICONS.get(item_id, item_id) + ".png")

    expected = {icon_path(item_id, group) for item_id, group, _ in items}
    actual = set().union(*[set((source / group).glob("*.png")) for group in ("equipment", "supplies")])
    if actual != expected:
        missing, extra = sorted(expected - actual), sorted(actual - expected)
        raise ValueError(f"PNG/catalog mismatch. Missing: {[p.name for p in missing]}. Extra: {[p.name for p in extra]}.")
    digests = {}
    for index, (item_id, group, appearance) in enumerate(items):
        tile = source_tile(icon_path(item_id, group))
        if group == "supplies":
            appearance = SOURCE_ICONS.get(item_id, item_id)
        digest = hashlib.sha256(tile.tobytes()).digest()
        if digest in digests and digests[digest][1] != appearance:
            raise ValueError(f"Duplicate icons: {item_id} and {digests[digest][0]}")
        digests[digest] = (item_id, appearance)
        sheet.paste(tile, (index % COLUMNS * CELL, index // COLUMNS * CELL))
    encoded = io.BytesIO()
    sheet.save(encoded, format="WEBP", quality=90, alpha_quality=100, method=6)
    with Image.open(io.BytesIO(encoded.getvalue())) as decoded:
        if decoded.size != sheet.size or ImageChops.difference(sheet.getchannel("A"), decoded.getchannel("A")).getbbox():
            raise ValueError("Encoded atlas lost size or alpha fidelity.")
    return encoded.getvalue(), stylesheet(items, rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sources", required=True, type=Path, help="Folder containing equipment and supplies")
    parser.add_argument("--node", default="node", help="Path to a compatible Node executable")
    parser.add_argument("--check", action="store_true", help="Validate source art and compare existing files")
    args = parser.parse_args()
    items = catalog(args.node)
    image, css = pack(items, args.sources)
    for path, data in [(ART, image), (CSS, css)]:
        if args.check:
            stored = path.read_bytes()
            if path == CSS:
                stored = stored.replace(b"\r\n", b"\n")
            if stored != data:
                raise ValueError(f"Rebuild needed: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{len(items)} icons. {COLUMNS * CELL}x{math.ceil(len(items) / COLUMNS) * CELL}. "
          f"{len(image):,} bytes WebP. SHA-256 {hashlib.sha256(image).hexdigest()}.")


if __name__ == "__main__":
    main()
