import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const assets=resolve(root,'public/assets');
const content=resolve(assets,'content');
const manifest='npc-v03-resident-face-rig-r1.json';
const roles=['blacksmith','elder-woman','farmer','herbalist','merchant','vigilante','youth'];
const json=path=>JSON.parse(readFileSync(path,'utf8'));
const hash=buf=>createHash('sha256').update(buf).digest('hex');
const variants={version:1,complete:true,assets:{}},models={};

// Infer bind-space facial coordinates from each model's own inverse bind.
// Z is the front of the authored glTF. The neck, jawline, scarf and hair behind
// the ears retain their authored weights. There is no runtime vertex pass.
for(const role of roles) {
 const id='moonforest-tripo-'+role;
 const row=json(resolve(assets,'npc-'+id+'.json')).assets[id];
 const g=json(resolve(assets,row.model));
 const primitive=g.meshes[0].primitives[0];
 const skin=g.skins[0],names=skin.joints.map(i=>g.nodes[i].name);
 const head=names.indexOf('mixamorig:Head');
 const unwanted=new Set(names.flatMap((name,i)=>/^mixamorig:(LeftShoulder|RightShoulder|Spine\d*)$/.test(name)?[i]:[]));
 const buffers=new Map();
 const accessor=index=>{
  const a=g.accessors[index],v=g.bufferViews[a.bufferView],uri=g.buffers[v.buffer].uri;
  if(!buffers.has(uri))buffers.set(uri,readFileSync(resolve(content,uri)));
  const buf=buffers.get(uri),width={SCALAR:1,VEC3:3,VEC4:4,MAT4:16}[a.type],bytes=a.componentType===5123?2:4;
  return {count:a.count,at(i,j){const offset=(v.byteOffset??0)+(a.byteOffset??0)+(v.byteStride??width*bytes)*i+j*bytes;return bytes===2?buf.readUInt16LE(offset):buf.readFloatLE(offset);}};
 };
 const ib=accessor(skin.inverseBindMatrices);
 const pos=[0,1,2].map(axis=>-[0,1,2].reduce((sum,i)=>sum+ib.at(head,axis*4+i)*ib.at(head,12+i),0));
 const attr=primitive.attributes,position=accessor(attr.POSITION),joints=accessor(attr.JOINTS_0),weights=accessor(attr.WEIGHTS_0);
 const rows=[];
 const smooth=x=>{x=Math.max(0,Math.min(1,x));return x*x*(3-2*x);};
 for(let i=0;i<position.count;i++){
  const y=position.at(i,1)-pos[1],z=position.at(i,2)-pos[2],x=Math.abs(position.at(i,0)-pos[0]);
  const strength=smooth((y-.005)/.024)*smooth((z-.017)/.032)*smooth((.112-x)/.025);
  if(!strength)continue;
  const bones=[0,1,2,3].map(j=>joints.at(i,j)),wp=bones.map((_,j)=>weights.at(i,j));
  const slot=bones.indexOf(head);
  if(slot<0||wp[slot]<.5)continue;
  let removed=0;
  for(let j=0;j<4;j++)if(unwanted.has(bones[j])){const w=wp[j]*strength;wp[j]-=w;removed+=w;}
  if(removed<.0005)continue;
  wp[slot]+=removed;
  rows.push({i,wp,removed});
 }
 if(!rows.length)throw Error('No face corrections for '+id);
 const indices=Buffer.alloc(rows.length*2),values=Buffer.alloc(rows.length*16);
 rows.forEach(({i,wp},n)=>{indices.writeUInt16LE(i,n*2);wp.forEach((v,j)=>values.writeFloatLE(v,n*16+j*4));});
 const padding=Buffer.alloc((4-indices.length%4)%4);
 const bytes=Buffer.concat([indices,padding,values]),uri=hash(bytes)+'.bin';
 writeFileSync(resolve(content,uri),bytes);
 const b=g.buffers.length,v=g.bufferViews.length;
 g.buffers.push({uri,byteLength:bytes.length});
 g.bufferViews.push({buffer:b,byteOffset:0,byteLength:indices.length},{buffer:b,byteOffset:indices.length+padding.length,byteLength:values.length});
 g.accessors[attr.WEIGHTS_0].sparse={count:rows.length,indices:{bufferView:v,componentType:5123},values:{bufferView:v+1}};
 const model=Buffer.from(JSON.stringify(g)),digest=hash(model);
 writeFileSync(resolve(content,digest+'.gltf'),model);
 models[id]=digest;
 variants.assets[id]={...row,model:'./content/'+digest+'.gltf',resources:[...row.resources,'./content/'+uri]};
 console.log(role,rows.length,'vertices',bytes.length,'new buffer bytes',Math.max(...rows.map(r=>r.removed)).toFixed(3),'max corrected weight');
}
writeFileSync(resolve(assets,manifest),JSON.stringify(variants,null,2)+'\n');
writeFileSync(resolve(root,'src/v03/resident-face-models.js'),
 "// Generated by repair-v03-resident-faces.mjs. All original meshes, textures and clips are reused.\n"+
 'const models = '+JSON.stringify(models,null,2)+';\n'+
 `export function withResidentFaceRig(entry) {
 const sha=models[entry.assetId];
 if(!sha)return entry;
 const manifest='assets/${manifest}';
 return {...entry,contentHash:sha,version:entry.version+'-face-r1',runtime:{...entry.runtime,
  manifest,model:'assets/content/'+sha+'.gltf',sources:[{manifest,assetKey:entry.assetId}]}};
}
`);
