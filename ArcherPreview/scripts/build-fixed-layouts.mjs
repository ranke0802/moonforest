// Prebuilds the fixed map layouts the game loads per region (src/generated/).
// The generators in src/village-layout.js and src/great-plains-layout.js stay
// the editing source; run this after changing them:
//   node scripts/build-fixed-layouts.mjs          write the generated modules (also run by npm run dev)
//   node scripts/build-fixed-layouts.mjs --check  fail when a module is stale
// tests/fixed-layouts.test.js runs the check, so a stale file fails CI.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const project=resolve(import.meta.dirname,'..'),target=resolve(project,'src/generated');
// Plains chapter points that take their position from a plains placement
// (chapter-quest-points.js): point id -> placement id.
export const PLAINS_POINT_PLACEMENTS=Object.freeze({'boundary-a':'boundary-a','boundary-b':'boundary-b',bandage:'saint-bandage'});

const header=source=>`// Generated by scripts/build-fixed-layouts.mjs from ${source}. Do not edit.\n`;
// JSON.parse of a string literal: the fastest form for engines to load, and the
// generators produce only plain objects, arrays, strings, booleans and finite numbers.
function dataModule(source,data){
 const json=JSON.stringify(data);
 if(JSON.stringify(JSON.parse(json))!==json)throw new Error('Placement data does not survive JSON: '+source);
 return header(source)+`export default JSON.parse(${JSON.stringify(json)});\n`;
}
export async function renderFixedLayouts(){
 const [{VILLAGE_PLACEMENTS},{PLAINS_PLACEMENTS}]=await Promise.all([import('../src/village-layout.js'),import('../src/great-plains-layout.js')]);
 // The quest apple tree is the village tree nearest the well (chapter quests).
 const tree=VILLAGE_PLACEMENTS.filter(p=>p.kind==='tree').sort((a,b)=>Math.hypot(a.x,a.z)-Math.hypot(b.x,b.z))[0]??null;
 const plainsPoints={};
 for(const [point,placementId]of Object.entries(PLAINS_POINT_PLACEMENTS)){
  const placement=PLAINS_PLACEMENTS.find(p=>p.id===placementId);
  if(placement)plainsPoints[point]={x:placement.x,z:placement.z};
 }
 const anchors=header('village-layout.js and great-plains-layout.js')+
  '// The few generated values that are needed before a region is loaded.\n'+
  `export const QUEST_APPLE_TREE_PLACEMENT=Object.freeze(${JSON.stringify(tree&&{id:tree.id,x:tree.x,z:tree.z})});\n`+
  `export const PLAINS_POINT_POSITIONS=Object.freeze(${JSON.stringify(plainsPoints)});\n`;
 return new Map([
  ['village-placements.js',dataModule('village-layout.js',VILLAGE_PLACEMENTS)],
  ['great-plains-placements.js',dataModule('great-plains-layout.js',PLAINS_PLACEMENTS)],
  ['fixed-layout-anchors.js',anchors],
 ]);
}
// A committed file is current when it matches the generator's output, or
// differs only by floating-point rounding (another Node/V8 version may round a
// Math.sin or Math.hypot result in its last bit). Everything else (order, IDs,
// kinds, a moved placement) is stale. The committed bytes are what ships.
const NUMBER=/-?\d+(?:\.\d+)?(?:e[+-]?\d+)?/gi;
export function sameLayoutText(a,b,tolerance=1e-9){
 if(a===b)return true;if(a==null||b==null)return false;
 if(a.replace(NUMBER,'#')!==b.replace(NUMBER,'#'))return false;
 const x=a.match(NUMBER)??[],y=b.match(NUMBER)??[];
 return x.length===y.length&&x.every((value,i)=>{const p=Number(value),q=Number(y[i]);return p===q||Math.abs(p-q)<=tolerance*Math.max(1,Math.abs(p),Math.abs(q));});
}
export async function checkFixedLayouts(){
 const stale=[];
 for(const [name,text]of await renderFixedLayouts()){
  const current=await readFile(resolve(target,name),'utf8').catch(()=>null);
  if(!sameLayoutText(current,text))stale.push(name);
 }
 return stale;
}
export async function assertFixedLayoutsCurrent(){
 const stale=await checkFixedLayouts();
 if(stale.length)throw new Error('Stale generated layouts (run node scripts/build-fixed-layouts.mjs): '+stale.join(', '));
}
if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
 if(process.argv.includes('--check')){
  try{await assertFixedLayoutsCurrent();console.log('Generated layouts are current.');}
  catch(error){console.error(error.message);process.exitCode=1;}
 }else{
  // Files that already match (rounding included) are left alone, so `npm run dev`
  // (predev) regenerates after a layout edit without touching unchanged files.
  await mkdir(target,{recursive:true});
  for(const [name,text]of await renderFixedLayouts()){
   const current=await readFile(resolve(target,name),'utf8').catch(()=>null);
   if(sameLayoutText(current,text))continue;
   await writeFile(resolve(target,name),text);console.log('wrote src/generated/'+name+' ('+Buffer.byteLength(text)+' bytes)');
  }
 }
}
