"""Strip the embedded authoring JPEG; reuse the chief's KTX2 by its content URL."""
import argparse
import hashlib
import json
import struct
from pathlib import Path

p=argparse.ArgumentParser()
p.add_argument('model', type=Path)
args=p.parse_args()
public=Path(__file__).resolve().parents[1]/'public/assets'
def write_blob(data, ext):
    path=public/'content'/(hashlib.sha256(data).hexdigest()+ext)
    path.write_bytes(data)
    return path.name

b=args.model.read_bytes()
length=struct.unpack_from('<I',b,12)[0]
model=json.loads(b[20:20+length])
blob=b[28+length:]
original=json.loads((public/'npc-moonforest-tripo-merchant.json').read_text('utf8'))
chief=next(iter(original['assets'].values()))
texture=next(path for path in chief['resources'] if path.endswith('.ktx2')).split('/')[-1]
image=model['images'][0].pop('bufferView')
views=model['bufferViews']
rebuilt=bytearray()
remap={}
for index,view in enumerate(views):
    if index==image: continue
    while len(rebuilt)%4:rebuilt.append(0)
    offset=view.get('byteOffset',0)
    remap[index]=len(remap)
    view['byteOffset']=len(rebuilt)
    rebuilt.extend(blob[offset:offset+view['byteLength']])
model['bufferViews']=[v for i,v in enumerate(views) if i!=image]
for accessor in model['accessors']:
    accessor['bufferView']=remap[accessor['bufferView']]
model['images']=[{'uri':texture,'mimeType':'image/ktx2'}]
for t in model['textures']:
    t['extensions']={'KHR_texture_basisu':{'source':t.pop('source')}}
model['extensionsUsed']=['KHR_texture_basisu']
model['extensionsRequired']=['KHR_texture_basisu']
# Blender baked constant channels beside the four useful motion channels.
for action in model['animations']:
    useful=[]
    for channel in action['channels']:
        output=model['accessors'][action['samplers'][channel['sampler']]['output']]
        if output.get('type')=='VEC4' and model['nodes'][channel['target']['node']].get('name')!='Root':
            useful.append(channel)
    old=action['samplers']
    action['samplers']=[old[c['sampler']] for c in useful]
    for i,c in enumerate(useful):c['sampler']=i
    action['channels']=useful
binname=write_blob(bytes(rebuilt),'.bin')
model['buffers']=[{'uri':binname,'byteLength':len(rebuilt)}]
header=write_blob(json.dumps(model,separators=(',',':')).encode(),'.gltf')
manifest={'version':1,'complete':True,'assets':{'sword-instructor':{'model':'./content/'+header,'resources':['./content/'+binname,'./content/'+texture]}}}
(public/'v03-seated-instructor-r1.json').write_text(json.dumps(manifest,indent=2)+'\n','utf8')
src=public.parents[1]/'src/v03/seated-instructor-asset.js'
src.write_text("// Generated by pack-v03-instructor.py. Meshes share the village chief's texture.\nexport const INSTRUCTOR_MODEL = 'assets/content/"+header+"';\n",'utf8')
print(header,binname,len(rebuilt),texture)

